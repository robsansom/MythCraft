function detectLanguage() {
  const saved = localStorage.getItem("mythcraft-lang");
  if (saved && I18N_SUPPORTED.includes(saved)) return saved;
  for (const raw of navigator.languages || [navigator.language || "en"]) {
    const base = raw.slice(0, 2).toLowerCase();
    if (I18N_SUPPORTED.includes(base)) return base;
  }
  return "en";
}

let currentLang = detectLanguage();

/** Look up a key in the active language (used by main.js for demo chrome). */
function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || null;
}

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("mythcraft-lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    // Remember the English source once, so switching back works.
    if (!el.dataset.i18nSource) el.dataset.i18nSource = el.innerHTML;
    const value = (I18N[lang] && I18N[lang][key]) || el.dataset.i18nSource;
    el.innerHTML = value;
  });

  const dict = I18N[lang] || {};
  if (dict["meta.title"]) document.title = dict["meta.title"];
  const desc = document.querySelector('meta[name="description"]');
  if (desc && dict["meta.description"]) desc.content = dict["meta.description"];

  const select = document.getElementById("lang-select");
  if (select) select.value = lang;
}

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(currentLang);
  const select = document.getElementById("lang-select");
  if (select) {
    select.addEventListener("change", () => applyLanguage(select.value));
  }
});
